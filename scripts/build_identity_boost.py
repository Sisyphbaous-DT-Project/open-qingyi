def pool_for(who):
    if who == "gege":
        return GEGE
    if who == "qunyou":
        return QUNYOU
    return GEGE + QUNYOU

def main():
    entries = {}  # 按 (问, 答) 去重
    # 1) 基准 persona_qa.json
    base = json.load(open(ROOT / "data/persona/persona_qa.json"))
    for e in base:
        entries[(e["q"], e["a"])] = ("gege", e["q"], e["a"])
    # 2) 变体组
    for ans, qs, who in GROUPS:
        for q in qs:
            entries.setdefault((q, ans), (who, q, ans))
            if q.endswith("？"):  # 无问号变体
                q2 = q[:-1]
                entries.setdefault((q2, ans), (who, q2, ans))

    items = list(entries.values())
    print(f"独特QA: {len(items)}")

    out = []
    for who, q, a in items:
        pool = pool_for(who)
        for _ in range(COPIES):
            name = random.choice(pool)
            out.append({"context": [{"role": "user", "name": name, "text": q}],
                        "target": a, "source": "identity"})
    n_identity = len(out)

    # 3) 混入聊天记录防过拟合
    chat = [json.loads(l) for l in open(ROOT / "data/sft/all_pairs_v4.jsonl")]
    random.shuffle(chat)
    for c in chat[:CHAT_MIX]:
        c["source"] = "chat"
        out.append(c)

    random.shuffle(out)
    dst = ROOT / "data/sft/boost_pairs.jsonl"
    with open(dst, "w") as f:
        for r in out:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"身份QA: {n_identity}  聊天: {min(CHAT_MIX, len(chat))}  总计: {len(out)} -> {dst}")

if __name__ == "__main__":
    main()
